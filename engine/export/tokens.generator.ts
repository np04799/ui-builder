/** Merge project branding over defaults to get the final token set */
function resolveTokens(branding?: ProjectBranding): DesignTokenSet {
  const tokens = { ...DEFAULTS }
  if (branding?.primaryColor) tokens.colorPrimary = branding.primaryColor
  if (branding?.fontFamily)   tokens.fontPrimary  = `${branding.fontFamily}, sans-serif`
  return tokens
}

// ─── TypeScript output ───────────────────────────────────────────────────────

function toTS(tokens: DesignTokenSet): string {
  const entries = Object.entries(tokens)
    .map(([k, v]) => `  ${k}: '${v}',`)
    .join('\n')
  return `/**
 * Design Tokens — generated by BuilderPro
 * These values reflect your project's branding and BuilderPro design system.
 */
export const tokens = {
${entries}
} as const

export type DesignTokens = typeof tokens
`
}

// ─── JavaScript output ───────────────────────────────────────────────────────

function toJS(tokens: DesignTokenSet): string {
  const entries = Object.entries(tokens)
    .map(([k, v]) => `  ${k}: '${v}',`)
    .join('\n')
  return `/**
 * Design Tokens — generated by BuilderPro
 */
export const tokens = {
${entries}
}
`
}

// ─── SCSS output ─────────────────────────────────────────────────────────────

function toKebab(camel: string): string {
  return camel.replace(/([A-Z])/g, (m) => `-${m.toLowerCase()}`)
}

function toSCSS(tokens: DesignTokenSet): string {
  const vars = Object.entries(tokens)
    .map(([k, v]) => `$${toKebab(k)}: ${v};`)
    .join('\n')
  return `// Design Tokens — generated by BuilderPro
// Import this file in styles.scss: @use 'tokens' as *;

${vars}
`
}

// ─── CSS custom properties output ────────────────────────────────────────────

function toCSS(tokens: DesignTokenSet): string {
  const vars = Object.entries(tokens)
    .map(([k, v]) => `  --${toKebab(k)}: ${v};`)
    .join('\n')
  return `/* Design Tokens — generated by BuilderPro */
:root {
${vars}
}
`
}

// ─── Public API ──────────────────────────────────────────────────────────────

export interface TokensFile {
  filename: string
  content: string
}

export function generateTokensFile(params: {
  branding: ProjectBranding | undefined
  platform: OutputPlatform
  lang: 'typescript' | 'javascript'
}): TokensFile {
  const { branding, platform, lang } = params
  const tokens = resolveTokens(branding)

  if (platform === 'angular') {
    return { filename: 'src/tokens.scss', content: toSCSS(tokens) }
  }

  if (platform === 'html') {
    return { filename: 'tokens.css', content: toCSS(tokens) }
  }

  // React / Vue
  if (lang === 'javascript') {
    return { filename: 'src/tokens.js', content: toJS(tokens) }
  }
  return { filename: 'src/tokens.ts', content: toTS(tokens) }
}

/** Expose resolved token set for use in README generator */
export function resolveDesignTokens(branding?: ProjectBranding): DesignTokenSet {
  return resolveTokens(branding)
}
