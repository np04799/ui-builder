/**
 * Design Tokens Generator — BuilderPro
 *
 * Generates a design tokens file from project branding + BuilderPro defaults.
 * Output format varies by export target:
 *   - React / Vue (TS): tokens.ts  — named TS exports
 *   - React / Vue (JS): tokens.js  — named JS exports
 *   - Angular:          tokens.scss — SCSS variables
 *   - HTML:             tokens.css  — CSS custom properties
 */

import type { BuilderMode } from '@/types/builder.types'
import type { OutputPlatform, ProjectBranding } from '@/types/store.types'

